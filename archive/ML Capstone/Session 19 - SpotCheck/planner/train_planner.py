"""Train and evaluate the 5 planning models: Linear Regression (plain OLS) on SYNTHETIC targets.

Evaluation (same style as the price/rating models):
- 10-fold KFold CV (shuffle, random_state=1) and GroupKFold by restaurant_name (chains together)
- Hold-out: the 10 reference restaurants T01-T10 (synthetic extras + targets)
- Linear Regression assumption checks on the training data (RESET, Breusch-Pagan, Jarque-Bera)

Run:  python planner/generate_data.py && python planner/train_planner.py
Writes planner/models/planner_models.joblib, planner_metrics.json, planner_coefficients.csv,
planner/data/planner_reference.csv (T01-T10 predictions the tests check) and planner/EVALUATION.md.
"""
import json
from pathlib import Path

import joblib
import numpy as np
import pandas as pd
import statsmodels.api as sm
from sklearn.compose import ColumnTransformer
from sklearn.linear_model import LinearRegression
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score
from sklearn.model_selection import GroupKFold, KFold, cross_val_predict
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import OneHotEncoder
from statsmodels.stats.diagnostic import het_breuschpagan, linear_reset
from statsmodels.stats.stattools import jarque_bera

from plan_predict import CATEGORICAL, METRICS_PATH, MODEL_PATH, TARGETS

HERE = Path(__file__).resolve().parent
DATA = HERE / "data"


def pipeline(features: list[str]) -> Pipeline:
    cats = [f for f in features if f in CATEGORICAL]
    encode = ColumnTransformer([("onehot", OneHotEncoder(handle_unknown="ignore", drop="first"), cats)],
                               remainder="passthrough")
    return Pipeline([("encode", encode), ("ols", LinearRegression())])


def scores(y, pred) -> dict:
    return {"mae": mean_absolute_error(y, pred), "rmse": float(np.sqrt(mean_squared_error(y, pred))),
            "r2": r2_score(y, pred)}


def assumption_checks(model: Pipeline, X: pd.DataFrame, y: pd.Series) -> dict:
    design = model.named_steps["encode"].transform(X)
    design = np.asarray(design.toarray() if hasattr(design, "toarray") else design, dtype=float)
    ols = sm.OLS(y.to_numpy(float), sm.add_constant(design, has_constant="add")).fit()
    reset = linear_reset(ols, power=2, use_f=True)
    bp = het_breuschpagan(ols.resid, ols.model.exog)
    jb, jb_p, skew, kurt = jarque_bera(ols.resid)
    return {"reset_p": float(reset.pvalue), "bp_p": float(bp[1]), "jb_p": float(jb_p),
            "skew": float(skew), "kurtosis": float(kurt)}


def fmt_p(p: float) -> str:
    return "< 0.001" if p < 0.001 else f"{p:.3f}"


def main() -> None:
    train = pd.read_csv(DATA / "planner_train.csv", keep_default_na=False)
    holdout = pd.read_csv(DATA / "planner_holdout.csv", keep_default_na=False)
    models, metrics, coef_rows = {}, {}, []
    reference = holdout[["TestID", "restaurant_name"]].copy()

    for target, spec in TARGETS.items():
        X, y = train[spec["features"]], train[target]
        kfold = cross_val_predict(pipeline(spec["features"]), X, y, cv=KFold(10, shuffle=True, random_state=1))
        group = cross_val_predict(pipeline(spec["features"]), X, y, cv=GroupKFold(10),
                                  groups=train["restaurant_name"])
        model = pipeline(spec["features"]).fit(X, y)
        hold_pred = model.predict(holdout[spec["features"]])
        cv, gcv, hold = scores(y, kfold), scores(y, group), scores(holdout[target], hold_pred)
        metrics[target] = {"cv_mae": cv["mae"], "cv_rmse": cv["rmse"], "cv_r2": cv["r2"],
                           "group_r2": gcv["r2"], "holdout_mae": hold["mae"], "holdout_r2": hold["r2"],
                           **assumption_checks(model, X, y)}
        models[target] = model
        reference[f"{target} (actual)"] = holdout[target]
        reference[f"{target} (predicted)"] = hold_pred.round(3)

        names = model.named_steps["encode"].get_feature_names_out()
        coef_rows.append({"target": target, "term": "intercept", "coefficient": model.named_steps["ols"].intercept_})
        for name, coef in zip(names, model.named_steps["ols"].coef_):
            coef_rows.append({"target": target, "term": name.split("__", 1)[1], "coefficient": coef})

    MODEL_PATH.parent.mkdir(exist_ok=True)
    joblib.dump(models, MODEL_PATH)
    METRICS_PATH.write_text(json.dumps(metrics, indent=2))
    pd.DataFrame(coef_rows).round(4).to_csv(MODEL_PATH.parent / "planner_coefficients.csv", index=False)
    reference.to_csv(DATA / "planner_reference.csv", index=False)
    write_report(metrics)
    print(pd.DataFrame(metrics).T.round(3))


def write_report(metrics: dict) -> None:
    lines = [
        "# Planner models – evaluation (SYNTHETIC data)",
        "",
        "Generated by `train_planner.py`. Targets are synthetic: a linear formula of the inputs plus normal noise",
        "(`generate_data.py`), so Linear Regression is correct by construction and high R² is expected.",
        "These numbers show the pipeline works; they are **not** evidence about real Bangalore restaurants.",
        "",
        "| Target | CV MAE | CV RMSE | CV R² | GroupKFold R² | Hold-out MAE (10) | Hold-out R² |",
        "|---|---|---|---|---|---|---|",
    ]
    for t, m in metrics.items():
        unit = TARGETS[t]["unit"]
        lines.append(f"| {TARGETS[t]['label']} ({unit}) | {m['cv_mae']:.2f} | {m['cv_rmse']:.2f} | {m['cv_r2']:.3f} | "
                     f"{m['group_r2']:.3f} | {m['holdout_mae']:.2f} | {m['holdout_r2']:.3f} |")
    lines += [
        "",
        "## Linear Regression assumption checks (training data, p-values; p > 0.05 = no evidence of a problem)",
        "",
        "| Target | Linearity (RESET) | Equal spread (Breusch–Pagan) | Normal errors (Jarque–Bera) | Skew | Kurtosis |",
        "|---|---|---|---|---|---|",
    ]
    for t, m in metrics.items():
        lines.append(f"| {TARGETS[t]['label']} | {fmt_p(m['reset_p'])} | {fmt_p(m['bp_p'])} | {fmt_p(m['jb_p'])} | "
                     f"{m['skew']:.2f} | {m['kurtosis']:.2f} |")
    lines += [
        "",
        "Reading the p-values: 15 tests at the 5% level are expected to give about 1 false alarm by chance, and with",
        "9,234 rows these tests flag even tiny departures. Skew ≈ 0 and kurtosis ≈ 3 (a perfect bell curve) show the",
        "errors are effectively normal. Food cost has a lower R² by design: its noise is large relative to its inputs.",
        "",
        "Independence: the synthetic noise is drawn independently per row, so chains do not share errors;",
        "GroupKFold R² ≈ KFold R² confirms it. Small departures can come from the few targets raised to a",
        "physical minimum in `generate_data.py` (printed when it runs).",
    ]
    (HERE / "EVALUATION.md").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
